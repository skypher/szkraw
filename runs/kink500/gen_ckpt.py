"""Checkpoint states for the Lean kernel certificate of the N = 500 one-kink example of P3 (r = 1/10, m = 450,
delta = 1/10): the windowed column state `(lo_{m-1}, H_{m-1}|window, lo_m, H_m|window)` of `Szkraw.ColCheck.witer`
at the steps in CKPTS, written to lean/Szkraw/Kink500Data<m>.lean. Every window is cross-checked against the full
column `ccol`, and the final sign of H_N(N) is printed. Usage: gen_ckpt.py [--check] (--check: compare with the
committed files instead of writing them)."""
import sys, os, time
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'lean', 'Szkraw')
N, MK, U, W, R, RN = 500, 450, 1, 10, 10, 1          # kinkZ 450 1 10, r = RN/R = 1/10
CKPTS = (150, 250, 350)

inc = [W if j < MK else W + U for j in range(N)]
Dn = [0]
for j in range(N):
    Dn.append(Dn[-1] + inc[j])
A = [R * (Dn[N] - Dn[i]) for i in range(N + 1)]        # rA
B = [(R - RN) * Dn[i] for i in range(N + 1)]           # rB
C = [RN * Dn[i] for i in range(N + 1)]                 # rC
eG = lambda L, i: L[i] if 0 <= i < len(L) else 0
lo = lambda m: max(m, N - m)

def align(l1, l2, L):
    return [0] * (l1 - l2) + L if l2 <= l1 else L[l2 - l1:]

def wrstep(bm, k, cs, P, X, xp):
    out = []
    for i in range(min(len(cs), len(P), len(X))):
        a, b, c = cs[i]
        out.append(a * (X[i + 1] if i + 1 < len(X) else 0) + ((b - bm) * X[i] + (c * xp - k * P[i])))
        xp = X[i]
    return out

def wstep(m, s):
    loP, P, loX, X = s
    loN = lo(m + 1)
    xp = (X[0] if X else 0) if loX < loN else 0
    coef = list(zip(A, zip(B, C)))[loN:]
    coef = [(a, bc[0], bc[1]) for a, bc in coef]
    return (loX, X, loN, wrstep(eG(B, m), eG(C, m) * eG(A, m - 1), coef, align(loP, loN, P), align(loX, loN, X), xp))

# full column (ccol) for the cross-check
Pf, Xf = [0] * (N + 1), [1 if n == N else 0 for n in range(N + 1)]
s = (N, [0], N, [1])
states = {}
t0 = time.time()
for m in range(N):
    kk = eG(C, m) * eG(A, m - 1)
    Yf = [A[n] * eG(Xf, n + 1) + (B[n] - B[m]) * Xf[n] + C[n] * (Xf[n - 1] if n >= 1 else 0) - kk * Pf[n] for n in range(N + 1)]
    Pf, Xf = Xf, Yf
    s = wstep(m, s)
    mm = m + 1
    lp = N if mm == 0 else lo(mm - 1)
    assert s[0] == lp and s[2] == lo(mm), mm
    assert s[1] == Pf[lp:] and s[3] == Xf[lo(mm):], f'window mismatch at step {mm}'
    if mm in CKPTS:
        states[mm] = s
    if mm % 50 == 0:
        print(f'[{time.strftime("%H:%M:%S")}] step {mm}/{N} cross-checked, window {len(s[3])}, '
              f'max digits {max(len(str(abs(v))) for v in s[3])}, {time.time() - t0:.1f}s', flush=True)
print('H_N(N) sign', (s[3][0] > 0) - (s[3][0] < 0), 'digits', len(str(abs(s[3][0]))))

def lean_list(L):
    return '[' + ',\n  '.join(str(v) for v in L) + ']'

def render(m, st):
    loP, P, loX, X = st
    return (f'import Szkraw.WindowColumn\n\n'
            f'/-! Windowed column state of the `N = 500` one-kink example (P3, Section 9) at step `{m}`, generated by\n'
            f'`runs/kink500/gen_ckpt.py`: `(lo_{{{m - 1}}}, H_{{{m - 1}}} on [{loP}, 500], lo_{{{m}}}, H_{{{m}}} on [{loX}, 500])`. -/\n\n'
            f'namespace Szkraw.ColCheck\n\n'
            f'/-- The state of `witer` for the `N = 500` example at step `{m}`. -/\n'
            f'def kink500ck{m} : WState := ({loP},\n  {lean_list(P)},\n  {loX},\n  {lean_list(X)})\n\n'
            f'end Szkraw.ColCheck\n')

check = '--check' in sys.argv
for m, st in states.items():
    path = os.path.join(OUT, f'Kink500Data{m}.lean')
    txt = render(m, st)
    if check:
        same = os.path.exists(path) and open(path).read() == txt
        print(f'{os.path.basename(path)}: {"IDENTICAL" if same else "DIFFERENT"}')
    else:
        open(path, 'w').write(txt)
        print(f'wrote {os.path.basename(path)}: {len(txt)} bytes')
